#!/usr/bin/env node
/**
 * Regenerates src/lib/modelCatalog/priceSnapshot.ts — the bundled price list Ergo falls back to when LiteLLM's
 * price JSON can't be fetched and the bridge has no cache.
 *
 *   node scripts/update-model-snapshot.mjs                 # fetch LiteLLM's live list
 *   node scripts/update-model-snapshot.mjs --input f.json  # use a downloaded copy instead
 *
 * ERGO_MODEL_PRICES_URL overrides the source URL (as for the bridge). The normalization is the bridge's own
 * (src/lib/modelCatalog/normalize.ts), imported directly through Node's built-in TypeScript type stripping
 * (Node ≥ 22.18 / 23.6; on older 22.x run with `node --experimental-strip-types`).
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DEFAULT_PRICES_URL = 'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';
const FETCH_TIMEOUT_MS = 10_000;
const MAX_BODY_BYTES = 20 * 1024 * 1024;
/** Fewer models than this means the list (or the normalization) is broken; don't overwrite a good snapshot with it. */
const MIN_MODELS = 20;

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'src/lib/modelCatalog/priceSnapshot.ts');

async function loadNormalizer() {
  try {
    return await import('../src/lib/modelCatalog/normalize.ts');
  } catch (err) {
    if (err && (err.code === 'ERR_UNKNOWN_FILE_EXTENSION' || err.code === 'ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING')) {
      console.error(`This script imports TypeScript directly and needs Node ≥ 22.18 (found ${process.version}). On older 22.x, run it with --experimental-strip-types.`);
      process.exit(1);
    }
    throw err;
  }
}

async function fetchCapped(url) {
  const res = await fetch(url, { signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) });
  if (!res.ok) throw new Error(`HTTP ${res.status} from ${url}`);
  const declared = Number(res.headers.get('content-length'));
  if (declared > MAX_BODY_BYTES) throw new Error(`Response is larger than ${MAX_BODY_BYTES} bytes.`);
  const reader = res.body.getReader();
  const chunks = [];
  let total = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.byteLength;
    if (total > MAX_BODY_BYTES) {
      await reader.cancel().catch(() => {});
      throw new Error(`Response is larger than ${MAX_BODY_BYTES} bytes.`);
    }
    chunks.push(value);
  }
  return Buffer.concat(chunks).toString('utf-8');
}

function argValue(flag) {
  const i = process.argv.indexOf(flag);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const { normalizeLiteLlmPrices } = await loadNormalizer();

const input = argValue('--input');
const source = input ? path.resolve(input) : process.env.ERGO_MODEL_PRICES_URL || DEFAULT_PRICES_URL;
const text = input ? await fs.readFile(source, 'utf-8') : await fetchCapped(source);
const models = normalizeLiteLlmPrices(JSON.parse(text));
if (models.length < MIN_MODELS) {
  console.error(`Only ${models.length} models after normalization (expected at least ${MIN_MODELS}); not writing the snapshot.`);
  process.exit(1);
}

const fetchedAt = new Date().toISOString();
const body = [
  '/**',
  ' * Bundled model prices — the last-resort fallback for the model catalog when LiteLLM\'s price list can\'t be fetched',
  ' * and the bridge has no cache. Generated by scripts/update-model-snapshot.mjs; do not edit by hand.',
  ` * Source: ${input ? 'LiteLLM model_prices_and_context_window.json (local copy)' : DEFAULT_PRICES_URL}`,
  ' */',
  "import type { ModelCatalog } from './types.ts';",
  '',
  'export const PRICE_SNAPSHOT: ModelCatalog = {',
  `  fetchedAt: ${JSON.stringify(fetchedAt)},`,
  "  sources: { prices: 'snapshot', benchmarks: 'none' },",
  '  models: [',
  ...models.map((m) => `    ${JSON.stringify(m)},`),
  '  ],',
  '};',
  '',
].join('\n');

await fs.writeFile(outFile, body, 'utf-8');

const counts = {};
for (const m of models) counts[m.provider] = (counts[m.provider] ?? 0) + 1;
console.log(`Wrote ${path.relative(root, outFile)}: ${models.length} models (${Object.entries(counts).map(([p, n]) => `${p} ${n}`).join(', ')}).`);
